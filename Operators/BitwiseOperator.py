print(6 & 3) # returns 0010, which is 2 in decimal.
# The binary representation of 6 is 0110
# The binary representation of 3 is 0011

print(6 | 3) # returns 0111, which is 7 in decimal.
# The binary representation of 6 is 0110
# The binary representation of 3 is 0011

print(6 ^ 3) # returns 0101, which is 5 in decimal.
# The binary representation of 6 is 0110
# The binary representation of 3 is 0011


print(~3)
print(3 << 2)
print(8 >> 2)
